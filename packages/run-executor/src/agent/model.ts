function stableSortObjectKeys(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => stableSortObjectKeys(entry));
  }

  if (value && typeof value === "object") {
    const record = value as Record<string, unknown>;
    const keys = Object.keys(record).sort((a, b) => a.localeCompare(b));
    const sorted: Record<string, unknown> = {};
    for (const key of keys) {
      sorted[key] = stableSortObjectKeys(record[key]);
    }
    return sorted;
  }

  return value;
}

export function canonicalizeModelPayload(modelPayload: Record<string, unknown>): Record<string, unknown> {
  return stableSortObjectKeys(modelPayload) as Record<string, unknown>;
}

function toolSortKey(tool: Tool): string {
  const toolRecord = tool as unknown as Record<string, unknown>;
  const type = typeof toolRecord.type === "string" ? toolRecord.type : "unknown";
  const name = typeof toolRecord.name === "string" ? toolRecord.name : "";
  return `${type}:${name}`;
}

export function normalizeToolsForRequest(tools: Tool[]): Tool[] {
  return [...tools].sort((left, right) => {
    return toolSortKey(left).localeCompare(toolSortKey(right));
  });
}

export type ModelToolChoice = "required" | "auto" | {
  type: "function";
  name: string;
};

type CreateModelResponseInput = {
  models: ModelGateway;
  purpose?: ModelCallPurpose;
  // ChatGPT Codex takes the prompt prefix as instructions instead of input items.
  chatGptCodex: boolean;
  modelType?: PlatformModelType;
  compatibilityModes?: PlatformModelCompatibilityMode[];
  requestTimeoutMs?: number;
  abortSignal?: AbortSignal;
  cacheUserId?: string;
  promptCacheKey?: string;
  // Defaults to the prompt cache key; swarm lanes send their own.
  sessionAffinityKey?: string;
  promptCacheTtl?: "30m";
  cacheKeepaliveSeconds?: number;
  prefixItems: ResponseInputItem[];
  conversationItems: ResponseInputItem[];
  modelPayload: Record<string, unknown>;
  maxOutputTokens?: number;
  tools: Tool[];
  toolChoice?: ModelToolChoice;
  parallelToolCalls?: boolean;
  headers?: Record<string, string>;
  requestAttempt?: number;
  requestSessionId?: string;
  acceptCutOffResponse?: boolean;
};

// Proxies that resume upstream sessions (e.g. Meridian) key conversations on this header;
// without it every tool round replays as a fresh session and loses the prompt cache.
// Meridian also keeps that session's prompt cache warm for the requested window.
function buildModelRequestHeaders(
  input: Pick<CreateModelResponseInput, "promptCacheKey" | "sessionAffinityKey" | "cacheKeepaliveSeconds">
): Record<string, string> {
  const affinityKey = input.sessionAffinityKey || input.promptCacheKey;
  if (typeof affinityKey !== "string" || affinityKey.length === 0) {
    return {};
  }
  return {
    "x-session-affinity": affinityKey,
    ...(input.cacheKeepaliveSeconds ? { "x-meridian-cache-keepalive": String(input.cacheKeepaliveSeconds) } : {})
  };
}

function buildModelRequestPayload(input: CreateModelResponseInput): Record<string, unknown> {
  const chatGptCodex = input.chatGptCodex;
  const modelType = input.modelType ?? "openai";
  const requestInput = normalizeProviderRequestInput(
    [...(chatGptCodex ? [] : input.prefixItems), ...input.conversationItems],
    modelType,
    input.compatibilityModes ?? []
  );
  const normalizedModelPayload = canonicalizeModelPayload(input.modelPayload);
  const normalizedTools = normalizeToolsForRequest(normalizeProviderRequestTools(input.tools, modelType));
  const promptCacheOptions: Record<string, unknown> = {};

  if (typeof input.promptCacheKey === "string" && input.promptCacheKey.length > 0) {
    promptCacheOptions.prompt_cache_key = input.promptCacheKey;
  }
  if (!chatGptCodex && input.promptCacheTtl === "30m") {
    promptCacheOptions.prompt_cache_options = {
      ttl: input.promptCacheTtl
    };
  }

  const requestPayload: Record<string, unknown> = {
    ...normalizedModelPayload,
    ...(input.maxOutputTokens ? { max_output_tokens: input.maxOutputTokens } : {}),
    ...promptCacheOptions,
    input: requestInput,
    include: ["reasoning.encrypted_content"],
    store: false,
    tools: normalizedTools,
    tool_choice: input.toolChoice ?? "required",
    parallel_tool_calls: input.parallelToolCalls ?? (normalizedModelPayload.parallel_tool_calls as boolean | undefined) ?? true,
    ...(!chatGptCodex && typeof input.cacheUserId === "string" && input.cacheUserId.length > 0
      ? { user: input.cacheUserId }
      : {})
  };

  if (chatGptCodex) {
    const instructions = buildChatGptCodexInstructions(input.prefixItems);
    if (instructions.length > 0) {
      requestPayload.instructions = instructions;
    }
  }

  return requestPayload;
}

export async function createModelResponse(input: CreateModelResponseInput): Promise<ModelGatewayResult> {
  const requestHeaders = { ...buildModelRequestHeaders(input), ...(input.headers ?? {}) };
  const result = await input.models.create({
    purpose: input.purpose ?? "turn",
    body: buildModelRequestPayload(input),
    ...(Object.keys(requestHeaders).length > 0 ? { headers: requestHeaders } : {}),
    timeoutMs: resolveRequestTimeoutMs(input.requestTimeoutMs),
    signal: input.abortSignal,
    sessionId: input.requestSessionId,
    attempt: input.requestAttempt ?? 1
  });
  const response = result.response;
  if (response.error) {
    throw Object.assign(new Error(response.error.message), {
      error: response.error
    });
  }

  for (const item of response.output) {
    if (item.type === "function_call" && (typeof item.call_id !== "string" || item.call_id.length === 0)) {
      throw new Error("Model response contained a function call without a call_id.");
    }
  }
  if (!input.acceptCutOffResponse && isRetryableCutOffResponse(response)) {
    throw new ModelResponseCutOffError();
  }

  return result;
}

const MODEL_REQUEST_MAX_RETRIES = 5;
const MODEL_REQUEST_BASE_DELAY_MS = 15_000;
const MODEL_REQUEST_RECOVERY_ERROR_THRESHOLD = 3;
const DEFAULT_MODEL_REQUEST_TIMEOUT_MS = 5 * 60 * 1000;

function resolveRequestTimeoutMs(requestTimeoutMs: number | undefined): number {
  if (typeof requestTimeoutMs !== "number" || !Number.isFinite(requestTimeoutMs)) {
    return DEFAULT_MODEL_REQUEST_TIMEOUT_MS;
  }

  const floored = Math.floor(requestTimeoutMs);
  return floored > 0 ? floored : DEFAULT_MODEL_REQUEST_TIMEOUT_MS;
}

async function sleepWithOptionalAbort(ms: number, signal: AbortSignal | undefined): Promise<void> {
  throwIfAborted(signal);

  await new Promise<void>((resolve, reject) => {
    const timeout = setTimeout(() => {
      if (signal) {
        signal.removeEventListener("abort", onAbort);
      }
      resolve();
    }, ms);

    function onAbort(): void {
      clearTimeout(timeout);
      reject(getAbortError(signal) ?? new Error("TASK_CANCELLED"));
    }

    if (signal) {
      signal.addEventListener("abort", onAbort, { once: true });
    }
  });
}

export async function createModelResponseWithRetry(
  control: RunControl,
  taskId: string,
  input: CreateModelResponseInput & {
    onConsecutiveErrorRecovery?: (errorMessage: string) => Promise<boolean>;
  },
  onRetryMessage?: (message: string) => Promise<void>
): Promise<ModelGatewayResult> {
  let lastError: Error | null = null;
  let consecutiveErrorCount = 0;
  let cutOffCount = 0;
  let attempt = 0;
  const requestSessionId = input.requestSessionId ?? taskId;
  const affinityKey = input.sessionAffinityKey || input.promptCacheKey;
  const requestInput = { ...input, ...resolveModelRequestSession(input.models, requestSessionId, affinityKey) };
  throwIfAborted(input.abortSignal);

  while (attempt <= MODEL_REQUEST_MAX_RETRIES) {
    throwIfAborted(input.abortSignal);
    const attemptNo = attempt + 1;
    try {
      return await createModelResponse({
        ...requestInput,
        requestAttempt: attemptNo,
        acceptCutOffResponse: cutOffCount >= MODEL_RESPONSE_CUT_OFF_RETRIES
      });
    } catch (err) {
      if (
        err instanceof Error
        && (err.message === "TASK_CANCELLED" || err.message === "RUN_TIME_LIMIT_REACHED")
      ) {
        throw err;
      }

      const abortError = getAbortError(input.abortSignal);
      if (abortError) {
        throw abortError;
      }

      lastError = err instanceof Error ? err : new Error(String(err));
      consecutiveErrorCount = isRecoverableModelInputError(err) ? consecutiveErrorCount + 1 : 0;
      if (err instanceof ModelResponseCutOffError) {
        cutOffCount += 1;
      }

      if (resolveModelErrorAction(lastError) !== null || isTerminalModelError(err)) {
        throw lastError;
      }

      if (isModelSessionConflictError(err)) {
        Object.assign(requestInput, resolveModelRequestSession(input.models, requestSessionId, affinityKey, true));
      }

      const isMissingToolOutput = parseMissingToolOutputCallId(lastError.message) !== null;
      if (
        attempt < MODEL_REQUEST_MAX_RETRIES
        && (consecutiveErrorCount >= MODEL_REQUEST_RECOVERY_ERROR_THRESHOLD || isMissingToolOutput)
        && input.onConsecutiveErrorRecovery
        && await input.onConsecutiveErrorRecovery(lastError.message)
      ) {
        consecutiveErrorCount = 0;
        attempt += 1;
        continue;
      }

      if (attempt === MODEL_REQUEST_MAX_RETRIES) {
        break;
      }

      const delayMs = MODEL_REQUEST_BASE_DELAY_MS * Math.pow(2, attempt);
      const retryMsg = `Model request failed (attempt ${attempt + 1}/${MODEL_REQUEST_MAX_RETRIES + 1}): ${lastError.message}. Retrying in ${(delayMs / 1000).toFixed(0)}s...`;

      if (onRetryMessage) {
        await onRetryMessage(retryMsg);
      }
      await control.emitEvent("error", {
        message: retryMsg,
        attempt: attempt + 1,
        maxAttempts: MODEL_REQUEST_MAX_RETRIES + 1,
        retrying: true
      });

      await sleepWithOptionalAbort(delayMs, input.abortSignal);
      attempt += 1;
    }
  }

  throw lastError!;
}

export async function maybeAutoGenerateTaskTitle(input: {
  control: RunControl;
  models: ModelGateway;
  chatGptCodex: boolean;
  taskId: string;
  currentTitle: string | null;
  source: TaskSource;
  messages: TaskMessageRow[];
  taskInputDir?: string | null;
  memoryMainFile?: MemoryMainFile | null;
  projectMemoryMainFile?: MemoryMainFile | null;
  imageDetail?: WorkspaceImageDetail;
  compatibilityModes?: PlatformModelCompatibilityMode[];
  requestTimeoutMs?: number;
  abortSignal?: AbortSignal;
}): Promise<void> {
  if (input.abortSignal?.aborted) {
    return;
  }

  const existingTitle = input.currentTitle?.trim() ?? "";
  if (existingTitle.length > 0 && !isAutoGeneratedTitlePlaceholder(existingTitle)) {
    return;
  }

  const firstUserMessage = input.messages.find((message) => message.role === "user");
  if (!firstUserMessage) {
    return;
  }

  const firstMessageText = asText(firstUserMessage.content_json).trim();
  const firstMessageHasAttachments =
    Array.isArray(firstUserMessage.content_json.attachments)
    && firstUserMessage.content_json.attachments.length > 0;
  if (firstMessageText.length === 0 && !firstMessageHasAttachments) {
    return;
  }

  try {
    const decisionContext = await buildTaskDecisionContext({
      messages: input.messages,
      taskInputDir: input.taskInputDir,
      memoryMainFile: input.memoryMainFile,
      projectMemoryMainFile: input.projectMemoryMainFile,
      imageDetail: input.imageDetail,
      mode: "first_user"
    });
    const titlePromptItems: ResponseInputItem[] = [
      {
        role: "system",
        content: TASK_TITLE_SYSTEM_PROMPT
      },
      {
        role: "user",
        content: [
          "Summarize the task using the bounded context below.",
          "Use the user's request as the primary signal; use attachment and memory context only to make the title more specific.",
          "",
          decisionContext.text,
          "",
          "Remember: output only the task title text."
        ].join("\n")
      },
      ...decisionContext.imageItems
    ];
    const titleRequestItems = input.chatGptCodex
      ? titlePromptItems.slice(1)
      : titlePromptItems;
    const requestInput = normalizeProviderRequestInput(titleRequestItems, "openai", input.compatibilityModes ?? []);
    const { response: titleResponse } = await input.models.create({
      purpose: "title",
      body: {
        ...(input.chatGptCodex ? { instructions: TASK_TITLE_SYSTEM_PROMPT } : {}),
        input: requestInput,
        tools: [TASK_TITLE_FUNCTION_TOOL],
        tool_choice: {
          type: "function",
          name: TASK_TITLE_TOOL_NAME
        },
        parallel_tool_calls: false,
        max_output_tokens: 32,
        store: false
      },
      sessionId: input.taskId,
      timeoutMs: resolveRequestTimeoutMs(input.requestTimeoutMs),
      signal: input.abortSignal
    });
    if (titleResponse.error) {
      return;
    }

    const titleToolCall = titleResponse.output.find(
      (outputItem): outputItem is ResponseFunctionToolCall =>
        isFunctionCallItem(outputItem) && outputItem.name === TASK_TITLE_TOOL_NAME
    );
    if (!titleToolCall) {
      return;
    }

    const parsedArguments = parseToolArguments(TASK_TITLE_TOOL_NAME, titleToolCall.arguments, taskTitleArgumentsSchema);
    if (!parsedArguments.ok) {
      return;
    }

    const normalizedTitle = normalizeTitleCandidate(parsedArguments.value.title);
    if (!normalizedTitle) {
      return;
    }

    const taggedTitle = applySourceTitlePrefix(normalizedTitle, input.source);
    if (!taggedTitle) {
      return;
    }

    await input.control.setGeneratedTitle(taggedTitle);
  } catch {
    // Title generation is a best-effort enhancement and should never fail the run.
  }
}
