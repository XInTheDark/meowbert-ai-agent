export function stripProviderManagedItemId(item: ResponseInputItem): ResponseInputItem {
  if (typeof item !== "object" || item === null || !("id" in item)) {
    return item;
  }

  if ("type" in item && item.type === "compaction") {
    return item;
  }

  const { id: _ignoredId, ...rest } = item as ResponseInputItem & { id?: string };
  return rest as ResponseInputItem;
}

type ResponseToolCallKind = "function_call" | "custom_tool_call" | "apply_patch_call";

function getResponseToolCallKind(item: ResponseInputItem): ResponseToolCallKind | null {
  if (typeof item !== "object" || item === null || !("type" in item) || !("call_id" in item)) {
    return null;
  }

  const record = item as unknown as { type?: unknown; call_id?: unknown };
  if (typeof record.call_id !== "string") {
    return null;
  }

  return record.type === "function_call" || record.type === "custom_tool_call" || record.type === "apply_patch_call"
    ? record.type
    : null;
}

function getResponseToolOutputType(kind: ResponseToolCallKind): string {
  return kind === "function_call"
    ? "function_call_output"
    : kind === "custom_tool_call"
      ? "custom_tool_call_output"
      : "apply_patch_call_output";
}

function isResponseToolOutput(item: ResponseInputItem): boolean {
  if (typeof item !== "object" || item === null || !("type" in item)) {
    return false;
  }

  const type = (item as unknown as { type?: unknown }).type;
  return type === "function_call_output" || type === "custom_tool_call_output" || type === "apply_patch_call_output";
}

function getCallId(item: ResponseInputItem): string | null {
  const callId = (item as { call_id?: unknown }).call_id;
  return typeof callId === "string" ? callId : null;
}

function isSyntheticRecoveredOutput(item: ResponseInputItem): boolean {
  if (typeof item !== "object" || item === null || !("output" in item)) {
    return false;
  }

  const output = (item as unknown as { output?: unknown }).output;
  return typeof output === "string" && output.includes("Recovered missing");
}

function buildRecoveredToolOutput(kind: ResponseToolCallKind, callId: string): ResponseInputItem {
  if (kind === "function_call") {
    return {
      type: "function_call_output",
      call_id: callId,
      output: JSON.stringify({ error: "Recovered missing function_call_output from historical task state." })
    };
  }

  if (kind === "custom_tool_call") {
    return {
      type: "custom_tool_call_output",
      call_id: callId,
      output: "Recovered missing custom_tool_call_output from historical task state."
    } as unknown as ResponseInputItem;
  }

  return {
    type: "apply_patch_call_output",
    call_id: callId,
    status: "failed",
    output: "Recovered missing apply_patch_call_output from historical task state."
  } as unknown as ResponseInputItem;
}

function parseToolMessageResponseItems(content: Record<string, unknown>): ResponseInputItem[] {
  const entries: Array<[string, string]> = [
    ["response_function_call", "function_call"],
    ["response_function_output", "function_call_output"],
    ["response_custom_tool_call", "custom_tool_call"],
    ["response_custom_tool_output", "custom_tool_call_output"],
    ["response_apply_patch_call", "apply_patch_call"],
    ["response_apply_patch_output", "apply_patch_call_output"]
  ];

  return entries.flatMap(([key, type]) => {
    const raw = content[key];
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      return [];
    }
    return [{ ...(raw as Record<string, unknown>), type } as ResponseInputItem];
  });
}

/**
 * Give every tool call in `items` exactly one output, keeping everything already present in its
 * original order. Replayed history must match what the provider saw, or its prompt cache misses
 * from that point on. A call with no output gets the real one from `fallbackItems` when it exists,
 * otherwise a placeholder, placed after the call's batch. Duplicate calls, duplicate outputs and
 * outputs without a call are dropped, since providers reject them.
 */
export function reconstructResponseInputItems(
  items: ResponseInputItem[],
  options: { omitReasoning?: boolean; fallbackItems?: ResponseInputItem[] } = {}
): ResponseInputItem[] {
  const normalizedItems = items
    .filter((item) => !options.omitReasoning || item.type !== "reasoning")
    .map((item) => stripProviderManagedItemId(item));
  const indexOutputs = (source: ResponseInputItem[]): Map<string, Array<{ index: number; item: ResponseInputItem }>> => {
    const outputs = new Map<string, Array<{ index: number; item: ResponseInputItem }>>();
    source.forEach((item, index) => {
      const callId = isResponseToolOutput(item) ? getCallId(item) : null;
      if (!callId) return;
      const entries = outputs.get(callId) ?? [];
      entries.push({ index, item });
      outputs.set(callId, entries);
    });
    return outputs;
  };
  const outputsByCall = indexOutputs(normalizedItems);
  const fallbackOutputsByCall = indexOutputs(options.fallbackItems ?? []);
  const outputsOfKind = (
    outputs: Map<string, Array<{ index: number; item: ResponseInputItem }>>,
    callId: string,
    kind: ResponseToolCallKind,
    after = -1
  ): ResponseInputItem[] => (outputs.get(callId) ?? [])
    .filter((entry) => entry.index > after && (entry.item as { type?: unknown }).type === getResponseToolOutputType(kind))
    .map((entry) => entry.item);
  const preferRealOutput = (candidates: ResponseInputItem[]): ResponseInputItem | undefined =>
    candidates.find((candidate) => !isSyntheticRecoveredOutput(candidate)) ?? candidates[0];

  const result: ResponseInputItem[] = [];
  const emittedCalls = new Map<string, ResponseToolCallKind>();
  const answeredCalls = new Set<string>();
  let owedOutputs: ResponseInputItem[] = [];

  normalizedItems.forEach((item, index) => {
    const kind = getResponseToolCallKind(item);
    const callId = getCallId(item);
    if (kind && callId) {
      if (emittedCalls.has(callId)) return;
      emittedCalls.set(callId, kind);
      result.push(item);
      if (outputsOfKind(outputsByCall, callId, kind, index).length === 0) {
        const fallback = preferRealOutput(outputsOfKind(fallbackOutputsByCall, callId, kind));
        owedOutputs.push(fallback ? stripProviderManagedItemId(fallback) : buildRecoveredToolOutput(kind, callId));
        answeredCalls.add(callId);
      }
      return;
    }

    if (isResponseToolOutput(item)) {
      const callKind = callId ? emittedCalls.get(callId) : undefined;
      if (!callId || !callKind || answeredCalls.has(callId)) return;
      const output = preferRealOutput(outputsOfKind(outputsByCall, callId, callKind));
      if (!output) return;
      answeredCalls.add(callId);
      result.push(output);
      return;
    }

    result.push(...owedOutputs, item);
    owedOutputs = [];
  });

  result.push(...owedOutputs);
  return result;
}

