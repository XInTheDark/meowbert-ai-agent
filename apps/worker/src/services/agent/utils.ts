const SUPPORTED_VIEW_IMAGE_MIME_TYPES = new Set([
  "image/png",
  "image/jpeg",
  "image/gif",
  "image/webp",
  "image/bmp"
]);

export async function detectImageMimeTypeFromBuffer(buffer: Buffer): Promise<string | null> {
  const detected = await fileTypeFromBuffer(buffer);
  if (!detected) {
    return null;
  }

  return SUPPORTED_VIEW_IMAGE_MIME_TYPES.has(detected.mime) ? detected.mime : null;
}

export function normalizeEnvironmentJsonPayload(rawPayload: unknown): Record<string, unknown> {
  const payload = isPlainObject(rawPayload)
    ? { ...rawPayload }
    : createDefaultEnvironmentJsonPayload();

  // Strip legacy field before response-payload normalization so it never leaks into `responses`.
  delete payload.max_context_window_tokens;

  const normalized = normalizeEnvironmentResponsesSettings(payload);
  return setSandboxNetworkEnabledOverride(normalized, getSandboxNetworkEnabledOverride(normalized));
}

export function extractModelRequestPayload(payload: Record<string, unknown>): Record<string, unknown> {
  return extractResponsesApiPayload(payload);
}

export function isNetworkRequestLoggingEnabled(payload: Record<string, unknown>): boolean {
  const debugConfig = payload.debug;
  if (!isPlainObject(debugConfig)) {
    return false;
  }

  return debugConfig.log_network_requests === true || debugConfig.logNetworkRequests === true;
}
