export function mergeTaskToolOptions(
  base: TaskMessageToolOptions,
  override?: TaskRunToolOptions | null
): TaskMessageToolOptions {
  if (!override) {
    return {
      webSearch: base.webSearch,
      memorySearch: base.memorySearch,
      scheduleTask: base.scheduleTask,
      subtasks: base.subtasks,
      computerUse: base.computerUse,
      interactiveCanvas: base.interactiveCanvas,
      enabledSkills: normalizeToolIdList(base.enabledSkills),
      enabledSources: normalizeToolIdList(base.enabledSources)
    };
  }

  const enabledSkills = Array.isArray(override.enabledSkills)
    ? normalizeToolIdList(override.enabledSkills)
    : normalizeToolIdList(base.enabledSkills);
  const enabledSources = Array.isArray(override.enabledSources)
    ? normalizeToolIdList(override.enabledSources)
    : normalizeToolIdList(base.enabledSources);

  return {
    webSearch: typeof override.webSearch === "boolean" ? override.webSearch : base.webSearch,
    memorySearch: typeof override.memorySearch === "boolean" ? override.memorySearch : base.memorySearch,
    scheduleTask: typeof override.scheduleTask === "boolean" ? override.scheduleTask : base.scheduleTask,
    subtasks: typeof override.subtasks === "boolean" ? override.subtasks : base.subtasks,
    computerUse: typeof override.computerUse === "boolean" ? override.computerUse : base.computerUse,
    interactiveCanvas: typeof override.interactiveCanvas === "boolean" ? override.interactiveCanvas : base.interactiveCanvas,
    enabledSkills,
    enabledSources
  };
}

function deepCloneJsonValue(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => deepCloneJsonValue(entry));
  }

  if (isPlainObject(value)) {
    const cloned: Record<string, unknown> = {};
    for (const [key, entry] of Object.entries(value)) {
      cloned[key] = deepCloneJsonValue(entry);
    }
    return cloned;
  }

  return value;
}

export function deepMergeJsonObjects(
  base: Record<string, unknown>,
  override: Record<string, unknown>
): Record<string, unknown> {
  const merged: Record<string, unknown> = {};
  const keys = new Set([...Object.keys(base), ...Object.keys(override)]);

  for (const key of keys) {
    const hasOverride = Object.prototype.hasOwnProperty.call(override, key);
    if (!hasOverride) {
      merged[key] = deepCloneJsonValue(base[key]);
      continue;
    }

    const overrideValue = override[key];
    const baseValue = base[key];
    if (isPlainObject(baseValue) && isPlainObject(overrideValue)) {
      merged[key] = deepMergeJsonObjects(baseValue, overrideValue);
      continue;
    }

    merged[key] = deepCloneJsonValue(overrideValue);
  }

  return merged;
}

function isFinalResponseFunctionCallItem(item: ResponseInputItem): item is ResponseInputItem & {
  type: "function_call";
  call_id: string;
  name: "final_response";
} {
  return typeof item === "object"
    && item !== null
    && "type" in item
    && item.type === "function_call"
    && "name" in item
    && item.name === "final_response"
    && "call_id" in item
    && typeof item.call_id === "string";
}

function isFunctionCallOutputForCallId(item: ResponseInputItem, callIds: Set<string>): boolean {
  return typeof item === "object"
    && item !== null
    && "type" in item
    && item.type === "function_call_output"
    && "call_id" in item
    && typeof item.call_id === "string"
    && callIds.has(item.call_id);
}

function hasAssistantInputItem(items: ResponseInputItem[]): boolean {
  return items.some((item) => (
    typeof item === "object"
    && item !== null
    && "role" in item
    && item.role === "assistant"
    && "content" in item
  ));
}

function asPersistedResponseInputItem(rawItem: unknown): ResponseInputItem | null {
  if (!rawItem || typeof rawItem !== "object") {
    return null;
  }

  const candidate = rawItem as { type?: unknown; role?: unknown; content?: unknown };
  if (typeof candidate.type === "string") {
    return rawItem as ResponseInputItem;
  }

  if (typeof candidate.role === "string" && candidate.content !== undefined) {
    return rawItem as ResponseInputItem;
  }

  return null;
}

function parsePersistedResponseItems(message: TaskMessageRow): ResponseInputItem[] {
  const content = message.content_json;
  const rawItems = content.response_items;
  if (!Array.isArray(rawItems)) {
    return [];
  }

  const items: ResponseInputItem[] = [];
  const finalResponseCallIds = new Set<string>();

  for (const rawItem of rawItems) {
    const item = asPersistedResponseInputItem(rawItem);
    if (!item) {
      continue;
    }

    if (isFinalResponseFunctionCallItem(item)) {
      finalResponseCallIds.add(item.call_id);
      continue;
    }

    items.push(item);
  }

  if (finalResponseCallIds.size === 0) {
    return items;
  }

  const filteredItems = items.filter((item) => !isFunctionCallOutputForCallId(item, finalResponseCallIds));
  const visibleText = typeof content.text === "string" ? content.text.trim() : "";
  if (
    message.role === "assistant"
    && visibleText.length > 0
    && !hasAssistantInputItem(filteredItems)
  ) {
    filteredItems.push(buildAssistantHistoryItem(visibleText));
  }

  return filteredItems;
}

function resolveMessageText(text: string, taskInputDir: string): string {
  // Normalize both legacy ../inputs/ references and current inputs/ references to the
  // absolute task inputs directory path so the model sees a single unambiguous location.
  return text.replace(
    /(^|[\s([{"'])(?:\.\.\/|\.\/)?inputs\//g,
    (_match, prefix: string) => `${prefix}${taskInputDir}/`
  );
}

interface TaskMessageAttachment {
  kind: "note" | "file" | "directory";
  label: string;
  content: string;
  relativePath?: string;
  sizeBytes?: number | null;
  forceInclude?: boolean;
}

function parseTaskMessageAttachments(content: Record<string, unknown>): TaskMessageAttachment[] {
  if (!Array.isArray(content.attachments)) {
    return [];
  }

  return content.attachments.reduce<TaskMessageAttachment[]>((attachments, rawAttachment) => {
    if (!rawAttachment || typeof rawAttachment !== "object") {
      return attachments;
    }

    const candidate = rawAttachment as {
      kind?: unknown;
      label?: unknown;
      content?: unknown;
      relativePath?: unknown;
      sizeBytes?: unknown;
      forceInclude?: unknown;
    };
    if (
      (candidate.kind !== "note" && candidate.kind !== "file" && candidate.kind !== "directory")
      || typeof candidate.label !== "string"
      || typeof candidate.content !== "string"
    ) {
      return attachments;
    }

    attachments.push({
      kind: candidate.kind,
      label: candidate.label,
      content: candidate.content,
      ...(typeof candidate.relativePath === "string" ? { relativePath: candidate.relativePath } : {}),
      ...(typeof candidate.sizeBytes === "number" && Number.isFinite(candidate.sizeBytes)
        ? { sizeBytes: candidate.sizeBytes }
        : candidate.sizeBytes === null
          ? { sizeBytes: null }
          : {}),
      ...(candidate.forceInclude === true ? { forceInclude: true } : {})
    });
    return attachments;
  }, []);
}

function resolveAttachmentAbsolutePath(attachment: TaskMessageAttachment, taskInputDir: string): string | null {
  const attachmentPath = attachment.relativePath ?? attachment.content;
  if (attachment.kind !== "file" || typeof attachmentPath !== "string" || attachmentPath.trim().length === 0) {
    return null;
  }

  const normalizedPath = attachmentPath.replace(/\\/g, "/").replace(/^\.?\//, "");
  if (normalizedPath === "inputs" || normalizedPath.startsWith("inputs/")) {
    return path.resolve(taskInputDir, normalizedPath === "inputs" ? "." : normalizedPath.slice("inputs/".length));
  }

  if (path.isAbsolute(attachmentPath)) {
    return path.resolve(attachmentPath);
  }

  return path.resolve(taskInputDir, attachmentPath);
}

function isLikelyTextAttachment(attachment: TaskMessageAttachment, filePath: string): boolean {
  const lowerName = `${attachment.label} ${filePath}`.toLowerCase();
  return /\.(txt|md|markdown|csv|tsv|json|jsonl|yaml|yml|xml|html|htm|css|js|jsx|ts|tsx|py|rb|go|rs|java|c|cc|cpp|h|hpp|sh|zsh|bash|sql|toml|ini|env|log)$/i.test(lowerName);
}

